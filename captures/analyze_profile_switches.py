KEY_LABELS = {
    0x04: 'A', 0x05: 'B', 0x06: 'C', 0x07: 'D', 0x08: 'E', 0x09: 'F',
    0x1e: '1', 0x1f: '2', 0x20: '3', 0x21: '4', 0x22: '5', 0x23: '6',
    0x24: '7', 0x25: '8', 0x26: '9', 0x27: '0', 0x2d: '-', 0x2e: '=',
    0x2b: 'Tab', 0x55: 'Num *', 0x59: 'Num 1', 0x5a: 'Num 2', 0x5b: 'Num 3',
    0x5c: 'Num 4', 0x5d: 'Num 5', 0x5e: 'Num 6', 0x5f: 'Num 7',
    0x60: 'Num 8', 0x61: 'Num 9', 0x62: 'Num 0', 0x63: 'Num .',
    0x07: 'D',
}

MOUSE_BTNS = {0x01: 'Left', 0x02: 'Right', 0x03: 'Middle', 0x04: 'Back', 0x05: 'Forward'}

def parse_packet(hex_str):
    h = hex_str.replace(":", "").replace(" ", "")
    if len(h) < 180:
        return None
    return {
        'status': int(h[0:2], 16),
        'trans_id': int(h[2:4], 16),
        'remaining': int(h[4:8], 16),
        'proto_type': int(h[8:10], 16),
        'data_size': int(h[10:12], 16),
        'cmd_class': int(h[12:14], 16),
        'cmd_id': int(h[14:16], 16),
        'args_hex': h[16:176],
        'crc': int(h[176:178], 16),
        'end': int(h[178:180], 16),
    }

def describe_action(action_type, params):
    if action_type == 0x00:
        return "Disabled"
    elif action_type == 0x01:
        btn = params[1]
        return f"Mouse {MOUSE_BTNS.get(btn, f'Btn {btn}')}"
    elif action_type == 0x02:
        mod = params[1]
        key = params[2]
        mod_str = ""
        if mod & 0x01: mod_str += "Ctrl+"
        if mod & 0x02: mod_str += "Shift+"
        if mod & 0x04: mod_str += "Alt+"
        if mod & 0x08: mod_str += "GUI+"
        return f"Key {mod_str}{KEY_LABELS.get(key, f'0x{key:02x}')}"
    elif action_type == 0x03:
        macro_id = (params[1] << 8) | params[2]
        return f"Macro 0x{macro_id:04x}"
    elif action_type == 0x06:
        x_dpi = (params[2] << 8) | params[3]
        y_dpi = (params[4] << 8) | params[5]
        return f"Sensitivity X={x_dpi} Y={y_dpi}"
    elif action_type == 0x0a:
        code = (params[1] << 8) | params[2]
        return f"Media 0x{code:04x}"
    elif action_type == 0x0c:
        return "Hypershift"
    else:
        return f"Type 0x{action_type:02x}"

def describe_command(p):
    cc = p['cmd_class']
    ci = p['cmd_id']
    ds = p['data_size']
    args = bytes.fromhex(p['args_hex'])

    if cc == 0x02 and ci == 0x0c:
        profile = args[0]
        btn_id = args[1]
        layer = args[2]
        action_type = args[3]
        params = list(args[4:10])
        layer_str = "Normal" if layer == 0 else "Hypershift"
        action_str = describe_action(action_type, params)
        return f"BUTTON WRITE: profile={profile} btn=0x{btn_id:02x} layer={layer_str} -> {action_str} (params={[f'0x{x:02x}' for x in params]})"

    elif cc == 0x05 and ci == 0x03:
        profile = args[0]
        return f"SET ACTIVE PROFILE: profile={profile}"

    elif cc == 0x05 and ci == 0x02:
        profile = args[0]
        return f"GET ACTIVE PROFILE: profile={profile}"

    elif cc == 0x05 and ci == 0x08:
        # Profile data - large payload
        profile = args[0]
        offset = (args[1] << 8) | args[2] if ds > 3 else 0
        chunk_size = args[3] if ds > 3 else 0
        # Check if it contains ASCII text
        text_part = args[4:4+min(64, ds)].decode('ascii', errors='replace')
        text_clean = ''.join(c if 32 <= ord(c) < 127 else '.' for c in text_part)
        return f"PROFILE DATA: profile={profile} offset=0x{offset:04x} size={chunk_size} data=\"{text_clean[:40]}\""

    elif cc == 0x04 and ci == 0x05:
        # DPI
        x_dpi = (args[0] << 8) | args[1]
        y_dpi = (args[2] << 8) | args[3]
        return f"SET DPI: X={x_dpi} Y={y_dpi}"

    elif cc == 0x04 and ci == 0x06:
        # DPI stages
        profile = args[0]
        num_stages = args[1]
        active = args[2]
        stages = []
        for i in range(num_stages):
            base = 3 + i * 7
            if base + 6 < len(args):
                stage_num = args[base]
                x = (args[base+1] << 8) | args[base+2]
                y = (args[base+3] << 8) | args[base+4]
                stages.append(f"stage{stage_num}={x}/{y}")
        return f"DPI STAGES: profile={profile} stages={num_stages} active={active} [{', '.join(stages)}]"

    elif cc == 0x06 and ci == 0x8e:
        return f"MACRO CLEAR (data_size={ds})"

    elif cc == 0x0f and ci == 0x80:
        return f"LED FX READ (data_size={ds}, args[0:2]={args[0]:02x} {args[1]:02x})"

    elif cc == 0x0f and ci == 0x84:
        return f"LED FX CONFIG (data_size={ds}, args[0:2]={args[0]:02x} {args[1]:02x})"

    elif cc == 0x0f and ci == 0x04:
        row = args[0]
        return f"LED SET COLOR: row=0x{row:02x} brightness=0x{args[1]:02x}"

    elif cc == 0x15 and ci == 0x00:
        return f"GET DEVICE MODE (args[0:2]={args[0]:02x} {args[1]:02x})"

    elif cc == 0x15 and ci == 0x07:
        count = args[0]
        ids = list(args[1:1+count])
        return f"LED LIST: count={count} ids={[f'0x{x:02x}' for x in ids]}"

    elif cc == 0x15 and ci == 0x80:
        profile = args[0]
        return f"GET BRIGHTNESS: profile={profile}"

    elif cc == 0x15 and ci == 0x88:
        return f"GET SERIAL"

    elif cc == 0x02 and ci == 0x16:
        return f"GET POLL RATE"

    elif cc == 0x04 and ci == 0x86:
        profile = args[0]
        return f"GET DPI: profile={profile}"

    elif cc == 0x00 and ci == 0x85:
        return f"GET SERIAL NUMBER"

    else:
        return f"CMD 0x{cc:02x}:0x{ci:02x} (data_size={ds}, args[0:4]={args[0]:02x} {args[1]:02x} {args[2]:02x} {args[3]:02x})"

# Parse and analyze
packets = []
for line in RAW_DATA.strip().split('\n'):
    parts = line.split('\t')
    if len(parts) != 2:
        continue
    ts = float(parts[0])
    p = parse_packet(parts[1])
    if p:
        packets.append((ts, p))

print(f"Total packets: {len(packets)}")
print(f"Time range: {packets[0][0]:.1f}s - {packets[-1][0]:.1f}s")
print()

# Group by time gaps
groups = []
current_group = [packets[0]]
for i in range(1, len(packets)):
    if packets[i][0] - packets[i-1][0] > 1.0:
        groups.append(current_group)
        current_group = [packets[i]]
    else:
        current_group.append(packets[i])
groups.append(current_group)

print(f"Found {len(groups)} command groups (separated by >1s gaps)")
print()

for gi, group in enumerate(groups):
    t_start = group[0][0]
    t_end = group[-1][0]
    print(f"=== Group {gi+1} @ t={t_start:.1f}s - {t_end:.1f}s ({len(group)} packets) ===")
    for ts, p in group:
        desc = describe_command(p)
        tid = p['trans_id']
        print(f"  [{ts:7.3f}s] tid=0x{tid:02x} {desc}")
    print()

# Summary
print("=== SUMMARY ===")
print()
cmd_counts = {}
for ts, p in packets:
    key = f"0x{p['cmd_class']:02x}:0x{p['cmd_id']:02x}"
    cmd_counts[key] = cmd_counts.get(key, 0) + 1

for key, count in sorted(cmd_counts.items()):
    print(f"  {key}: {count} packets")

print()
print("=== PROFILE SWITCH COMMANDS (0x05:0x03 / 0x05:0x02) ===")
for ts, p in packets:
    if p['cmd_class'] == 0x05 and p['cmd_id'] in (0x02, 0x03):
        args = bytes.fromhex(p['args_hex'])
        print(f"  [{ts:7.3f}s] {'SET' if p['cmd_id']==0x03 else 'GET'} PROFILE = {args[0]}")

print()
print("=== BUTTON MAPPING WRITES (0x02:0x0c) ===")
for ts, p in packets:
    if p['cmd_class'] == 0x02 and p['cmd_id'] == 0x0c:
        args = bytes.fromhex(p['args_hex'])
        profile = args[0]
        btn_id = args[1]
        layer = args[2]
        action_type = args[3]
        params = list(args[4:10])
        layer_str = "Normal" if layer == 0 else "HS"
        action_str = describe_action(action_type, params)
        print(f"  [{ts:7.3f}s] profile={profile} btn=0x{btn_id:02x} layer={layer_str} -> {action_str}")

print()
print("=== TRANSACTION IDs SEEN ===")
tids = set()
for ts, p in packets:
    tids.add(p['trans_id'])
print(f"  {sorted([f'0x{t:02x}' for t in tids])}")
